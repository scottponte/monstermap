"""Cut one sprite per icon type from the original art and write ../data/maps/<map>-icons.js for every built map."""
import json
import cv2
import numpy as np

IMG = cv2.imread('nh_full.jpg')
MASK = cv2.imread('night-harbor-mask.png', 0)
icons = json.load(open('night-harbor-snapped.json'))
OUT = '../assets/icons/'
SCALE = 3.6  # full-res px per map unit (1600-wide grid)


def isolation(ic):
    """How much of an icon's neighbourhood is covered by *other* icons (lower is better)."""
    x, y, r = int(ic['x']), int(ic['y']), ic['size'] // 2 + 6
    win = MASK[y - r:y + r, x - r:x + r]
    own = np.zeros_like(win)
    cv2.circle(own, (r, r), r - 4, 255, -1)
    return float(((win > 0) & (own == 0)).mean())


def save_rgba(name, bgr, alpha):
    out = cv2.cvtColor(bgr, cv2.COLOR_BGR2BGRA)
    out[..., 3] = alpha
    cv2.imwrite(OUT + name + '.png', out)


by_type = {}
for ic in icons:
    by_type.setdefault(ic['type'], []).append(ic)

made = {}
for typ, lst in by_type.items():
    if typ in ('humanoid', 'goblin', 'ring', 'star'):
        continue
    ic = min(lst, key=isolation)
    x, y = int(round(ic['x'])), int(round(ic['y']))
    if typ in ('bank', 'shady', 'inn', 'stable', 'stall'):
        # the legend has the same squares at higher resolution: crop tightly to the dark frame
        t = cv2.imread(f'tpl/{typ}.png')
        g = cv2.cvtColor(t, cv2.COLOR_BGR2GRAY)
        cnts, _ = cv2.findContours((g < 110).astype(np.uint8) * 255, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
        bx, by, bw, bh = max((cv2.boundingRect(c) for c in cnts), key=lambda b: b[2] * b[3])
        crop = cv2.resize(t[by:by + bh, bx:bx + bw], (72, 72), interpolation=cv2.INTER_AREA)
        save_rgba(typ, crop, np.full(crop.shape[:2], 255, np.uint8))
    else:  # round badge
        r = ic['size'] // 2 + 2
        crop = IMG[y - r:y + r, x - r:x + r].copy()
        a = np.zeros(crop.shape[:2], np.uint8)
        cv2.circle(a, (r, r), r - 1, 255, -1, cv2.LINE_AA)
        # anything inside the disc that isn't badge-grey or glyph-black (e.g. a banner poking in) -> badge grey
        hsv = cv2.cvtColor(crop, cv2.COLOR_BGR2HSV)
        inner = np.zeros_like(a); cv2.circle(inner, (r, r), r - 6, 255, -1)
        grey = (hsv[..., 1] < 35) & (hsv[..., 2] > 150) & (inner > 0)
        fill = np.median(crop[grey], axis=0) if grey.any() else np.array([190, 200, 205])
        stray = (inner > 0) & (hsv[..., 1] > 55) & (hsv[..., 2] > 90)
        crop[stray] = fill
        save_rgba(typ, crop, a)
    made[typ] = ic['id']

# Silhouettes (humanoid / goblin / generic-mob ring / respawn star) from the legend art, as white alpha masks
# so the app can tint them with the level colour.
LEG = {'humanoid': (603 + 1550, 428 + 200, 683 + 1550, 522 + 200), 'goblin': (868 + 1550, 298 + 200, 968 + 1550, 402 + 200),
       'ring': (598 + 1550, 322 + 200, 688 + 1550, 410 + 200), 'star': (862 + 1550, 428 + 200, 968 + 1550, 528 + 200)}
SD = cv2.imread('sd_full.jpg')  # Shaded Dunes legend adds undead / Ashira / giant
LEG_SD = {'skull': (4385, 480, 4470, 585), 'ashira': (4390, 575, 4460, 695), 'giant': (4668, 482, 4740, 595)}
for name, box in list(LEG.items()) + list(LEG_SD.items()):
    a, b, c, d = box
    src = SD if name in LEG_SD else IMG
    g = cv2.cvtColor(src[b:d, a:c], cv2.COLOR_BGR2GRAY)
    alpha = np.clip((140 - g.astype(np.int32)) * 3, 0, 255).astype(np.uint8)
    alpha = cv2.morphologyEx(alpha, cv2.MORPH_OPEN, np.ones((3, 3), np.uint8))
    ys, xs = np.where(alpha > 40)
    alpha = alpha[ys.min():ys.max() + 1, xs.min():xs.max() + 1]
    s = max(alpha.shape) + 4
    sq = np.zeros((s, s), np.uint8)
    oy, ox = (s - alpha.shape[0]) // 2, (s - alpha.shape[1]) // 2
    sq[oy:oy + alpha.shape[0], ox:ox + alpha.shape[1]] = alpha
    white = np.full((s, s, 3), 255, np.uint8)
    save_rgba('shape-' + name, white, sq)

# ---- data files (one per built map)
import os
for map_id in ('night-harbor', 'shaded-dunes'):
    if not os.path.exists(f'{map_id}-snapped.json'):
        continue
    data = []
    for ic in json.load(open(f'{map_id}-snapped.json')):
        d = {'id': ic['id'], 'type': ic['type'], 'x': round(ic['x'] / SCALE, 1), 'y': round(ic['y'] / SCALE, 1)}
        for k in ('color', 'letter', 'note'):
            if ic.get(k):
                d[k] = ic[k]
        data.append(d)
    body = '[\n' + ',\n'.join('  ' + json.dumps(d, ensure_ascii=False) for d in data) + ',\n]'
    js = ("// Icons that were painted on Maggot's map, now live markers. Generated by work/build.py + work/sprites.py;\n"
          '// positions are in map units (full-res px / 3.6). Edits made in the app are stored per browser, not here.\n'
          f"(window.NH_ICONS_BY_MAP = window.NH_ICONS_BY_MAP || {{}})['{map_id}'] = " + body + ';\n')
    os.makedirs('../data/maps', exist_ok=True)
    open(f'../data/maps/{map_id}-icons.js', 'w', encoding='utf-8').write(js)
    print(map_id, len(data), 'icons')
print('sprites', sorted(made))
